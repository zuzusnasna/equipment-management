-- ========================================
-- 09. 장비 상태 변경 이력
-- ========================================

CREATE TABLE EQUIPMENT_HISTORY (
    HISTORY_ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EQUIPMENT_ID                NUMBER NOT NULL,
    PREVIOUS_STATUS_CODE_ID     NUMBER NOT NULL,
    NEW_STATUS_CODE_ID          NUMBER NOT NULL,
    CHANGE_COMMENT              VARCHAR2(1000) NOT NULL,
    CHANGED_BY                  VARCHAR2(100) NOT NULL,
    CHANGED_AT                  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_EQUIPMENT_HISTORY
        PRIMARY KEY (HISTORY_ID),

    CONSTRAINT FK_EQUIPMENT_HISTORY_EQUIPMENT
        FOREIGN KEY (EQUIPMENT_ID)
        REFERENCES EQUIPMENT(EQUIPMENT_ID)
);

CREATE INDEX IDX_EQUIPMENT_HISTORY_EQUIPMENT
    ON EQUIPMENT_HISTORY(EQUIPMENT_ID, CHANGED_AT DESC);

COMMENT ON TABLE EQUIPMENT_HISTORY IS '장비 상태 변경 이력';
COMMENT ON COLUMN EQUIPMENT_HISTORY.EQUIPMENT_ID IS '장비 ID';
COMMENT ON COLUMN EQUIPMENT_HISTORY.PREVIOUS_STATUS_CODE_ID IS '변경 전 상태 코드 ID';
COMMENT ON COLUMN EQUIPMENT_HISTORY.NEW_STATUS_CODE_ID IS '변경 후 상태 코드 ID';
COMMENT ON COLUMN EQUIPMENT_HISTORY.CHANGE_COMMENT IS '변경 사유';
COMMENT ON COLUMN EQUIPMENT_HISTORY.CHANGED_BY IS '상태 변경 사용자';
COMMENT ON COLUMN EQUIPMENT_HISTORY.CHANGED_AT IS '상태 변경 일시';

COMMIT;
